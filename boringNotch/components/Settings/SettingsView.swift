    private var validatedVisualizerURL: URL? {
        let candidate = url.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let parsed = URL(string: candidate),
              let scheme = parsed.scheme?.lowercased(),
              ["https", "http"].contains(scheme),
              parsed.host != nil
        else { return nil }
        return parsed
    }

    private var canAddVisualizer: Bool {
        !name.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            && validatedVisualizerURL != nil
    }

    var body: some View {
        Form {
            Section {
                Toggle(
                    OffKeyL10n.text(
                        "offkey.settings.showShelfWhenEmpty",
                        fallback: "空文件架也显示“文件暂存”标签"
                    ),
                    isOn: $coordinator.alwaysShowTabs
                )
                Defaults.Toggle(key: .settingsIconInNotch) {
                    Text("Show settings icon in notch")
                }

            } header: {
                Text("General")
            }

            Section {
                Defaults.Toggle(key: .coloredSpectrogram) {
                    Text("Colored spectrogram")
                }
                Defaults
                    .Toggle("播放器配色", key: .playerColorTinting)
                Defaults.Toggle(key: .lightingEffect) {
                    Text("Enable blur effect behind album art")
                }
                OmniDWorkspaceChoicePicker(title: "Slider color", selection: $sliderColor,
                    choices: SliderColorEnum.allCases.map { ($0.rawValue, $0) })
            } header: {
                Text("Media")
            }

            Section {
                Toggle(
                    "使用音频频谱",
                    isOn: $useMusicVisualizer.animation()
                )
                if !useMusicVisualizer {
                    if customVisualizers.count > 0 {
                        OmniDWorkspaceChoicePicker(title: "当前动画", selection: $selectedVisualizer,
                            choices: customVisualizers.map { ($0.name, Optional($0)) })
                    } else {
                        HStack {
                            Text("当前动画")
                            Spacer()
                            Text("默认动画")
                                .foregroundStyle(.secondary)
                        }
                    }
                }
            } header: {
                HStack {
                    Text("音乐动效")
                }
            } footer: {
                Text("关闭音频频谱后，刘海会显示当前选择的 Lottie 动画；未添加自定义动画时使用内置默认效果。")
            }

            Section {
                List {
                    ForEach(customVisualizers, id: \.self) { visualizer in
                        HStack {
                            LottieView(
                                url: visualizer.url, speed: visualizer.speed,
                                loopMode: .loop
                            )
                            .frame(width: 30, height: 30, alignment: .center)
                            Text(visualizer.name)
                            Spacer(minLength: 0)
                            if selectedVisualizer == visualizer {
                                Text("已选择")
                                    .font(.caption)
                                    .fontWeight(.medium)
                                    .foregroundStyle(.secondary)
                                    .padding(.trailing, 8)
                            }
                        }
                        .buttonStyle(PlainButtonStyle())
                        .padding(.vertical, 2)
                        .background(
                            selectedListVisualizer != nil
                                ? selectedListVisualizer == visualizer
                                    ? Color.effectiveAccent : Color.clear : Color.clear,
                            in: RoundedRectangle(cornerRadius: 5)
                        )
                        .contentShape(Rectangle())
                        .onTapGesture {
                            if selectedListVisualizer == visualizer {
                                selectedListVisualizer = nil
                                return
                            }
                            selectedListVisualizer = visualizer
                        }
                    }
                }
                .safeAreaPadding(
                    EdgeInsets(top: 5, leading: 0, bottom: 5, trailing: 0)
                )
                .frame(minHeight: 120)
                .actionBar {
                    HStack(spacing: 5) {
                        Button {
                            name = ""
                            url = ""
                            speed = 1.0
                            isPresented.toggle()
                        } label: {
                            Image(systemName: "plus")
                                .foregroundStyle(.secondary)
                                .contentShape(Rectangle())
                        }
                        Divider()
                        Button {
                            if let visualizer = selectedListVisualizer {
                                OmniDWorkspaceNotice.confirm("移除这个动画？", message: "仅移除自定义动画配置，原文件会保留。", confirmTitle: "移除") {
                                    guard let index = customVisualizers.firstIndex(of: visualizer) else { return }
                                    selectedListVisualizer = nil
                                    customVisualizers.remove(at: index)
                                    if visualizer == selectedVisualizer {
                                        selectedVisualizer = customVisualizers.first
                                    }
                                }
                            }
                        } label: {
                            Image(systemName: "minus")
                                .foregroundStyle(.secondary)
                                .contentShape(Rectangle())
                        }
                    }
                }
                .controlSize(.small)
                .buttonStyle(PlainButtonStyle())
                .overlay {
                    if customVisualizers.isEmpty {
                        Text("尚未添加自定义动画")
                            .foregroundStyle(Color(.secondaryLabelColor))
                            .padding(.bottom, 22)
                    }
                }
                .sheet(isPresented: $isPresented) {
                    VStack(alignment: .leading) {
                        Text("添加 Lottie 动画")
                            .font(.largeTitle.bold())
                            .padding(.vertical)
                        TextField("名称", text: $name)
                        TextField("Lottie JSON URL", text: $url)
                        if !url.isEmpty && validatedVisualizerURL == nil {
                            Text("请输入完整的 http 或 https 地址。")
                                .font(.caption)
                                .foregroundStyle(.red)
                        }
                        HStack {
                            Text("播放速度")
                            Spacer(minLength: 80)
                            Text("\(speed, specifier: "%.1f")s")
                                .multilineTextAlignment(.trailing)
                                .foregroundStyle(.secondary)
                            Slider(value: $speed, in: 0...2, step: 0.1)
                        }
                        .padding(.vertical)
                        HStack {
                            Button {
                                isPresented.toggle()
                            } label: {
                                Text("取消")
                                    .frame(maxWidth: .infinity, alignment: .center)
                            }

                            Button {
                                guard let visualizerURL = validatedVisualizerURL else { return }
                                let visualizer: CustomVisualizer = .init(
                                    UUID: UUID(),
                                    name: name.trimmingCharacters(in: .whitespacesAndNewlines),
                                    url: visualizerURL,
                                    speed: speed
                                )

                                if !customVisualizers.contains(visualizer) {
                                    customVisualizers.append(visualizer)
                                    if selectedVisualizer == nil {
                                        selectedVisualizer = visualizer
                                    }
                                }

                                isPresented.toggle()
                            } label: {
                                Text("添加")
                                    .frame(maxWidth: .infinity, alignment: .center)
                            }
                            .buttonStyle(BorderedProminentButtonStyle())
                            .disabled(!canAddVisualizer)
                        }
                    }
                    .textFieldStyle(RoundedBorderTextFieldStyle())
                    .controlSize(.extraLarge)
                    .padding()
                }
            } header: {
                HStack(spacing: 0) {
                    Text("自定义动画（Lottie）")
                    if !Defaults[.customVisualizers].isEmpty {
                        Text(" – \(Defaults[.customVisualizers].count)")
                            .foregroundStyle(.secondary)
                    }
                }
            }

            Section {
                Defaults.Toggle(key: .showMirror) {
                    Text("Enable boring mirror")
                }
                    .disabled(!checkVideoInput())
                OmniDWorkspaceChoicePicker(title: "Mirror shape", selection: $mirrorShape,
                    choices: [("Circle", MirrorShapeEnum.circle), ("Square", .rectangle)])
                Defaults.Toggle(key: .showNotHumanFace) {
                    Text("Show cool face animation while inactive")
                }
            } header: {
                HStack {
                    Text("Additional features")
                }
            }
        }
        .accentColor(.effectiveAccent)
        .navigationTitle("Appearance")
    }

    func checkVideoInput() -> Bool {
        if AVCaptureDevice.default(for: .video) != nil {
            return true
        }

        return false
    }
}

